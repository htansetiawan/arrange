"""items.py — the edit suite: curated requests on the three canvases (Color Purple, Someday My Prince Will Come,
All the Things You Are), designed with the composer.

Every item has a KIND (the composer's real messages are mostly not single edits):
  single    one change at one place
  list      several separate changes in one message
  pattern   one change wherever something occurs ("every and", "no holds anywhere")
  passage   a span in his shorthand: words and/or pitches laid on notes (dictation, a new melody on the same rhythm,
            new words on the same notes)
  symptom   what he hears; the model must find the cause (from the sounds the singer gets, the note lengths) and the fix
  revision  refers to an earlier edit in the session (`history`; the fit already carries that edit, `pre`)
  question  asks for information, not an edit; the right answer says it (`say`: words the answer must contain)
Within a kind, each item varies three things (what / where / when):
  what   pitch, text, add (a note), delete, fit (which syllable on which note), sound (pronunciation), timing
  where  how the note is pointed at; every kind of reference the model must resolve is listed in `refs`:
         bar, beat, note (a pitch name), word, num (the canvas's grey number under a syllable), rel (before/after/
         between another note), short (the composer's shorthand: word (pitch pitch)), image (a canvas screenshot with the
         note circled)
  when   only for timing and added notes: exact (a beat), unit (a musical length), vague ("a tad late")
Difficulty grows with the number of references to combine and the number of dimensions changed.

complete=False: the request leaves out something the edit needs (which note, what pitch, how long); the right answer
is to ask. `accept` lists what counts: "ask", "gold", or both.

Bar and beat are as the canvas shows them (canvas_pos.py). Rows are 0-based fit rows (the canvas's data-row).
`pre` ops make the item's starting fit from the canvas fit (then rows are renumbered); `alts` lists other op lists
that count as right. Gold ops use the typed edit vocabulary; ("T", bar, beat) is a canvas position in seconds, ("mid", row) the middle
of that row's note. Requests are written in the style of the composer's own messages (lowercase, "..", note names in
parentheses, hyphenated syllables).
"""

